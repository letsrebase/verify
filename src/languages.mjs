// The languages a profile can be written in.
//
// A language is one entry in LANGUAGES: its code, its English name (the prompt
// tells the model "write in <name>"), and the label table `profile.md` is
// rendered from. Adding a language is one entry here and nothing else.
//
// The payload never changes with the language: enum values stay the English
// codes the detectors emit ("daily driver", "deep focus", ...). Only what a
// person reads goes through `labels`: headings, fixed phrases, and the display
// name of each code. A code with no label shows as itself.

