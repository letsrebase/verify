// name: the English name the prompt gives the model.
export const LANGUAGES = {
  it: { code: "it", name: "Italian", labels: IT },
  en: { code: "en", name: "English", labels: EN },
};

export const SUPPORTED_LANGUAGES = Object.keys(LANGUAGES);

export const isSupportedLanguage = (code) => Object.hasOwn(LANGUAGES, code);

// A profile with no `language` predates the field and was written in English.
export const labelsFor = (code) => (LANGUAGES[code] ?? LANGUAGES.en).labels;

// The display name of a payload code, or the code itself when the language has none.
export const codeLabel = (labels, code) => labels.codes[code] ?? code;
